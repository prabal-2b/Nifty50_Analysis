use nifty_50_data;

/*
CHEAKING HOW MANY TIMES MARKET OPEN WITH GAP UP OR UP THAN PREVIOUS CLOSING.
*/

-- WE DON'T HAVE COLUMN OR DATA OF PREIVOUS CLOSING BUT WE CAN EXTRACT FROM GIVEN DATA.

WITH TEMP AS (
	SELECT
		*,
		IFNULL(LAG(CLOSE) OVER(ORDER BY DATE),OPEN) AS Prev_Closing
	FROM NIFTY50_INDEX_DATA
    )

SELECT
	*,
    Total_mark_opened_days - Total_gap_up Total_gap_down
FROM (
	SELECT
		(
			SELECT
				COUNT(*)
			FROM NIFTY50_INDEX_DATA
		) AS Total_mark_opened_days,
		(
			SELECT
				COUNT(*)
			FROM TEMP
			WHERE PREV_CLOSING < OPEN
		) AS Total_gap_up
	) T
;


-- EXTRACTING PRICE ENCREAMENT OF NIFTY50.
WITH TEMP AS (
	SELECT
		YEAR(T1.DATE_NEW) AS Year,
		T1.OPEN,
		T2.CLOSE
	FROM (
		SELECT
			*
		FROM (
			SELECT
				*,
				MIN(DATE_NEW) OVER(PARTITION BY YEAR(DATE_NEW)) AS FIRST_OPENING_DAY,
				MAX(DATE_NEW) OVER(PARTITION BY YEAR(DATE_NEW)) AS LAST_OPENING_DAY
			FROM NIFTY50_INDEX_DATA
			) AS T
		WHERE (DATE_NEW = FIRST_OPENING_DAY OR DATE_NEW = LAST_OPENING_DAY) AND YEAR(DATE_NEW) < 2026
		ORDER BY 
			DATE_NEW
		) T1
	INNER JOIN (
		SELECT
			*
		FROM (
			SELECT
				*,
				MIN(DATE_NEW) OVER(PARTITION BY YEAR(DATE_NEW)) AS FIRST_OPENING_DAY,
				MAX(DATE_NEW) OVER(PARTITION BY YEAR(DATE_NEW)) AS LAST_OPENING_DAY
			FROM NIFTY50_INDEX_DATA
			) AS F
		WHERE (DATE_NEW = FIRST_OPENING_DAY OR DATE_NEW = LAST_OPENING_DAY) AND YEAR(DATE_NEW) < 2026
		ORDER BY 
			DATE_NEW
	) AS T2
	ON YEAR(T1.DATE_NEW) = YEAR(T2.DATE_NEW) AND T1.DATE_NEW < T2.DATE_NEW
	
    ) 

SELECT	
	*,
    ROUND(AVG(Per_year_price_gain) OVER(),2) AS avg_price_gain,
    MAX(Per_year_price_gain) OVER() AS max_price_gain
FROM (
	SELECT
		Year,
		ROUND(Close - Open,2) AS Per_year_price_gain
	FROM TEMP
    ) TEMP2;


